command = {
    (' ', 0):(' ', -1, 1),
    (' ',2): (' ', 2, 2),
    (' ', 3): (' ', 2, 3),
    ('1', 1):('1', -1,3),
    ('1',2):('0', -1, 1),
    ('1',3):('1',-1,2),
    ('0', 1):('0', -1, 3),
    ('0',2):('1', -1, 3),
    ('0',3):('0', -1, 2)
}

def mt(s):
    s = list(" " + s + " ")
    i = len(s) -1
    q = 0
    while True:
        cmd = command[(s[i], q)]
        s[i] = cmd[0]
        if cmd[1] == 2:
            break
        q = cmd[2]
        i+= cmd[1]
    return "".join(s)

print(mt('1' * 221).count('1'))
