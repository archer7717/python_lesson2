command = {
    (' ', 0): (' ', -1, 1),
    (' ', 1):(' ', 2, 1),
    (' ', 2):(' ', 2, 2),
    (' ', 3):(' ', 2, 3),
    ('1',1):('1', -1, 2),
    ('1', 2):('0', -1, 3),
    ('1',3):('1', -1, 1),
    ('0',1):('0', -1, 2),
    ('0', 2):('1', -1,3 ),
    ('0',3):('0', -1, 1)
}

def mt(s):
    s = list( " " + s + " ")
    q = 0
    i = len(s) -1
    while True:
        cmd = command[(s[i]), q]
        s[i] = cmd[0]
        if cmd[1] == 2:
            break
        q = cmd[2]
        i += cmd[1]
    return ''.join(s)

print(mt('0' * 12 + '1' * 15).replace(' ', '').count('0'))
